package com.eventplatform.core;

import com.eventplatform.model.event.EventHeaders;
import com.eventplatform.model.event.EventIdentifier;
import com.eventplatform.model.event.EventMetadata;
import com.eventplatform.model.event.EventStatus;
import com.eventplatform.model.event.EventTypeVersion;
import com.eventplatform.model.event.GenericEventEnvelope;

import java.time.Instant;
import java.util.Objects;

public class DefaultEventEnvelopeFactory implements EventEnvelopeFactory {

    private final EventPlatformCoreProperties properties;

    public DefaultEventEnvelopeFactory() {
        this(new EventPlatformCoreProperties());
    }

    public DefaultEventEnvelopeFactory(EventPlatformCoreProperties properties) {
        this.properties = Objects.requireNonNull(properties, "properties must not be null");
    }

    @Override
    public <T> GenericEventEnvelope<T> create(
            String eventType,
            String source,
            EventStatus status,
            T payload,
            EventProcessingContext context,
            EventHeaders headers,
            EventMetadata metadata
    ) {
        Objects.requireNonNull(eventType, "eventType must not be null");
        Objects.requireNonNull(source, "source must not be null");
        Objects.requireNonNull(status, "status must not be null");
        Objects.requireNonNull(payload, "payload must not be null");
        Objects.requireNonNull(context, "context must not be null");

        EventHeaders effectiveHeaders = headers == null ? EventHeaders.builder().build() : headers;
        EventMetadata effectiveMetadata = metadata == null ? buildMetadata(eventType, source, context) : metadata;

        return GenericEventEnvelope.<T>builder()
                .eventId(new EventIdentifier("evt-" + java.util.UUID.randomUUID()))
                .eventType(eventType)
                .eventTypeVersion(new EventTypeVersion(eventType, properties.getDefaultEventVersion()))
                .source(source)
                .status(status)
                .occurredAt(Instant.now())
                .metadata(effectiveMetadata)
                .headers(effectiveHeaders)
                .payload(payload)
                .build();
    }

    private EventMetadata buildMetadata(String eventType, String source, EventProcessingContext context) {
        return EventMetadata.builder()
                .eventType(eventType)
                .eventVersion(properties.getDefaultEventVersion())
                .source(source)
                .aggregateType(eventType.split("\\.")[0])
                .aggregateId(context.aggregateId())
                .occurredAt(Instant.now())
                .schemaVersion(properties.getDefaultEventVersion())
                .description("event generated by event-platform-core")
                .build();
    }
}
